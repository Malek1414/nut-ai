#!/usr/bin/env node
/**
 * Bundles the USDA rows the recipe table pins (src/dishes.ts `usda`) into
 * src/recipe-foods.generated.ts, so a scan of a known dish reads no database.
 *
 *   node scripts/gen-recipe-foods.mjs            write the file
 *   node scripts/gen-recipe-foods.mjs --check    exit 1 when the file is out of date
 *
 * Run it after editing a `usda` pin in src/dishes.ts or rebuilding the corpus.
 * Source: data/nutrition.db (npm run data:build), else the local D1 file that
 * `npm run db:setup` loads. A pin missing from the bundle still works: the
 * Worker falls back to a D1 query for it.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { DatabaseSync } from 'node:sqlite'
import { DISH_TABLE } from '../src/dishes.ts'

const APP = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(APP, 'src/recipe-foods.generated.ts')

function corpusPath() {
  const built = join(APP, 'data/nutrition.db')
  if (existsSync(built)) return built
  const d1 = join(APP, '.wrangler/state/v3/d1/miniflare-D1DatabaseObject')
  const file = existsSync(d1) ? readdirSync(d1).find((f) => f.endsWith('.sqlite') && f !== 'metadata.sqlite') : null
  if (file) return join(d1, file)
  throw new Error('No corpus found. Run `npm run db:setup` (or `npm run data:build`) first.')
}

const db = new DatabaseSync(corpusPath(), { readOnly: true })
const COLS = `id AS foodId, name, energy_kcal AS energyKcal, protein_g AS proteinG, fat_g AS fatG, carb_g AS carbG,
  fiber_g AS fiberG, sugar_g AS sugarG, sodium_mg AS sodiumMg, source, source_id AS sourceId`
// The corpus holds some descriptions twice (Foundation and SR Legacy). The id is
// picked with the exact statements the Worker has always used, so the bundle
// names the same row a live query would.
const exact = db.prepare('SELECT id FROM foods WHERE name = ? LIMIT 1')
const prefix = db.prepare('SELECT id FROM foods WHERE name LIKE ? ORDER BY length(name) LIMIT 1')
const byId = db.prepare(`SELECT ${COLS} FROM foods WHERE id = ?`)

const pins = [...new Set(DISH_TABLE.flatMap((d) => d.components.map((c) => c.usda).filter(Boolean)))].sort()
const rows = {}
const missing = []
for (const pin of pins) {
  const hit = (pin.endsWith('%') ? prefix : exact).get(pin)
  if (!hit) { missing.push(pin); continue }
  const row = byId.get(hit.id)
  rows[pin] = { ...row, foodId: String(row.foodId) }
}
if (missing.length) {
  console.error(`Not in the corpus:\n  ${missing.join('\n  ')}`)
  process.exit(1)
}

const text = `/**
 * GENERATED by scripts/gen-recipe-foods.mjs. Do not edit.
 * The USDA FoodData Central rows (per 100 g) that src/dishes.ts pins by description.
 */
import type { FoodRow } from './food-lookup.js'

export const RECIPE_FOODS: Record<string, FoodRow> = ${JSON.stringify(rows, null, 2)}
`

if (process.argv.includes('--check')) {
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== text) {
    console.error('src/recipe-foods.generated.ts is out of date. Run: node scripts/gen-recipe-foods.mjs')
    process.exit(1)
  }
  console.log(`recipe foods up to date (${pins.length} rows)`)
} else {
  writeFileSync(OUT, text)
  console.log(`wrote ${OUT} (${pins.length} rows)`)
}
